"""Hosted chat completions with ordered provider fallback."""

import json
import logging
import re
from collections.abc import AsyncGenerator

import httpx

import config

logger = logging.getLogger(__name__)


class LLMClient:
    """Generate answers through Groq, OpenRouter, then Vercel AI Gateway."""

    def __init__(self) -> None:
        providers = [
            (
                "Groq",
                "https://api.groq.com/openai/v1/chat/completions",
                config.GROQ_MODEL,
                config.GROQ_API_KEY,
            ),
            (
                "OpenRouter",
                "https://openrouter.ai/api/v1/chat/completions",
                config.OPENROUTER_MODEL,
                config.OPENROUTER_API_KEY,
            ),
            (
                "Vercel AI Gateway",
                "https://ai-gateway.vercel.sh/v1/chat/completions",
                config.VERCEL_AI_MODEL,
                config.AI_GATEWAY_API_KEY,
            ),
        ]
        self._providers = [provider for provider in providers if provider[3]]
        self._client = httpx.AsyncClient(timeout=config.LLM_TIMEOUT)
        logger.info("Configured language model providers: %s", ", ".join(
            provider[0] for provider in self._providers
        ) or "none")

    async def close(self) -> None:
        await self._client.aclose()

    async def is_available(self) -> bool:
        """Report whether at least one provider key is configured."""
        return bool(self._providers)

    async def generate(
        self, messages: list[dict[str, str]], stream: bool = False
    ) -> str | AsyncGenerator[str, None]:
        if stream:
            return self._generate_stream(messages)
        return await self._generate_full(messages)

    @staticmethod
    def _request(model: str, messages: list[dict[str, str]], stream: bool) -> dict:
        return {
            "model": model,
            "messages": messages,
            "stream": stream,
            "temperature": config.LLM_TEMPERATURE,
        }

    async def _generate_full(self, messages: list[dict[str, str]]) -> str:
        for name, url, model, key in self._providers:
            try:
                response = await self._client.post(
                    url,
                    headers={"Authorization": f"Bearer {key}"},
                    json=self._request(model, messages, False),
                )
                response.raise_for_status()
                content = response.json()["choices"][0]["message"]["content"]
                if not isinstance(content, str) or not content.strip():
                    raise ValueError("Empty model response")
                logger.info("Answer generated by %s", name)
                return content
            except (httpx.HTTPError, ValueError, KeyError, IndexError, TypeError) as exc:
                self._log_failure(name, exc)
        raise RuntimeError("All configured language model providers failed")

    async def _generate_stream(
        self, messages: list[dict[str, str]]
    ) -> AsyncGenerator[str, None]:
        for name, url, model, key in self._providers:
            emitted = False
            try:
                async with self._client.stream(
                    "POST",
                    url,
                    headers={"Authorization": f"Bearer {key}"},
                    json=self._request(model, messages, True),
                ) as response:
                    response.raise_for_status()
                    async for line in response.aiter_lines():
                        if not line.startswith("data:"):
                            continue
                        payload = line[5:].strip()
                        if payload == "[DONE]":
                            if not emitted:
                                raise ValueError("Empty model response")
                            logger.info("Answer streamed by %s", name)
                            return
                        data = json.loads(payload)
                        if not isinstance(data, dict):
                            raise TypeError("Invalid model response")
                        if data.get("error"):
                            raise ValueError("Provider stream error")
                        choices = data.get("choices") or []
                        if not choices:
                            continue
                        if not isinstance(choices, list) or not isinstance(choices[0], dict):
                            raise TypeError("Invalid model response")
                        delta = choices[0].get("delta") or {}
                        if not isinstance(delta, dict):
                            raise TypeError("Invalid model response")
                        content = delta.get("content")
                        if content is None:
                            continue
                        if not isinstance(content, str):
                            raise TypeError("Invalid model response")
                        if content:
                            emitted = True
                            yield content
                if emitted:
                    logger.info("Answer streamed by %s", name)
                    return
                raise ValueError("Empty model response")
            except (httpx.HTTPError, ValueError, KeyError, IndexError, TypeError) as exc:
                self._log_failure(name, exc)
                if emitted:
                    raise RuntimeError("Model stream interrupted") from exc
        raise RuntimeError("All configured language model providers failed")

    @staticmethod
    def _log_failure(name: str, exc: Exception) -> None:
        reason = (
            f"HTTP {exc.response.status_code}"
            if isinstance(exc, httpx.HTTPStatusError)
            else type(exc).__name__
        )
        logger.warning("%s language model request failed: %s", name, reason)

    async def expand_query(self, query: str) -> list[str]:
        """Ask a configured provider for alternative search wording."""
        expansion_prompt = (
            "You are a search query expansion assistant. Given the user's question "
            "about a book on habit formation ('Atomic Habits' by James Clear), "
            "generate exactly 3 alternative search queries that would help find "
            "relevant passages. Each alternative should:\n"
            "- Use different words/synonyms\n"
            "- Approach the topic from a slightly different angle\n"
            "- Be concise (under 15 words)\n\n"
            "Return ONLY the 3 queries, one per line, with no numbering or bullets."
        )
        messages = [
            {"role": "system", "content": expansion_prompt},
            {"role": "user", "content": query},
        ]
        response_text = await self._generate_full(messages)
        alternatives = [
            re.sub(r"^\s*(?:\d+[.)]|[-*])\s*", "", line).strip(" \"'")
            for line in response_text.splitlines()
            if line.strip()
        ]
        return alternatives[:3]
